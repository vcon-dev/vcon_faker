"""Synthetic-corpus governance markers for vCon syntax 0.5.0 (draft-ietf-vcon-vcon-core-05).

Every synthetic vCon carries exactly three markers, as in ``vcon-dev/fake-vcons`` and
``CONSENT.md``:

* a ``lawful_basis`` attachment with ``legitimate_interests``, the documented synthetic basis
  (approved by the fake-vcons repo owner 2026-09-25), ``expiration: null``, grants for
  recording, transcription, analysis and redistribution, and an ``external_system`` proof
  naming the generator;
* a ``tags`` attachment holding ``synthetic:true``;
* ``validation: "synthetic"`` on every party.

This module never writes any other basis. There is no real person, so there is no consent to
record, and a fabricated consent record is worse than none.

Ported from the ``modernize-phase-2`` branch (``vconbuild/builder.py``), which targets syntax
0.4.0. Under core-05 a vCon-level attachment is scoped by ``party`` plus ``session`` (not
``dialog: 0``), and with ``encoding: "json"`` the body is the JSON value itself, not a
``json.dumps`` string. Both attachments are built by vcon-lib (``add_tag``,
``add_lawful_basis_attachment``), the same helpers Smart Trunk's adapters use, so the tags
body is the array of ``name:value`` strings that the portal reads.
"""
from __future__ import annotations

from typing import Any

from vcon import Vcon
from vcon.extensions.lawful_basis.attachment import ProofMechanism, ProofType

SYNTHETIC_BASIS = "legitimate_interests"
SYNTHETIC_PURPOSES = ("recording", "transcription", "analysis", "redistribution")
GENERATOR = "vcon-faker"
TERMS_URL = "https://github.com/vcon-dev/vcon_faker/blob/main/CONSENT.md"
JUSTIFICATION = (
    "Synthetic conversation generated by vcon_faker (https://github.com/vcon-dev/vcon_faker); "
    "no real data subject"
)


def add_synthetic_governance(
    vcon: Vcon,
    *,
    at: str,
    session: int = 0,
    tags: dict[str, Any] | None = None,
    pipeline_note: str | None = None,
) -> None:
    """Add the tags and lawful_basis markers, and mark every party synthetic.

    Args:
        vcon: the vCon to mark. Call after its parties and Session exist.
        at: ISO 8601 time with a zone, used for ``start`` and ``granted_at``.
        session: the Session the basis covers (the whole call).
        tags: extra ``name:value`` tags; ``synthetic:true`` is always added first.
        pipeline_note: how the conversation was made, kept in the proof's ``proof_data``.
    """
    for party in vcon.vcon_dict.get("parties") or []:
        party["validation"] = "synthetic"

    vcon.add_tag("synthetic", "true")
    for name, value in (tags or {}).items():
        vcon.add_tag(name, str(value))
    _scope_tags(vcon, at, session)

    proof_data: dict[str, Any] = {"system": GENERATOR, "description": JUSTIFICATION}
    if pipeline_note:
        proof_data["note"] = pipeline_note
    vcon.add_lawful_basis_attachment(
        lawful_basis=SYNTHETIC_BASIS,
        expiration=None,
        purpose_grants=[
            {"purpose": p, "granted": True, "granted_at": at} for p in SYNTHETIC_PURPOSES
        ],
        party_index=0,
        session_index=session,
        proof_mechanisms=[ProofMechanism(ProofType.EXTERNAL_SYSTEM, timestamp=at, proof_data=proof_data)],
        terms_of_service=TERMS_URL,
        metadata={"synthetic": True, "justification": JUSTIFICATION, "license": "MIT"},
    )
    basis = vcon.vcon_dict["attachments"][-1]
    basis.setdefault("mediatype", "application/json")
    basis["start"] = at


def _scope_tags(vcon: Vcon, at: str, session: int) -> None:
    for attachment in vcon.vcon_dict.get("attachments") or []:
        if attachment.get("purpose") == "tags":
            attachment["start"] = at
            attachment["session"] = session
            attachment.pop("dialog", None)


def governance_problems(vcon_dict: dict[str, Any]) -> list[str]:
    """What is missing or wrong among the three synthetic markers. Empty means all present."""
    problems: list[str] = []
    attachments = vcon_dict.get("attachments") or []

    bases = [a for a in attachments if (a.get("purpose") or a.get("type")) == "lawful_basis"]
    if len(bases) != 1:
        problems.append(f"expected one lawful_basis attachment, found {len(bases)}")
    for basis in bases:
        body = basis.get("body")
        if not isinstance(body, dict):
            problems.append("lawful_basis body is not a JSON object")
            continue
        if body.get("lawful_basis") != SYNTHETIC_BASIS:
            problems.append(f"lawful_basis is {body.get('lawful_basis')!r}, not {SYNTHETIC_BASIS!r}")
        granted = {g.get("purpose") for g in body.get("purpose_grants") or [] if g.get("granted")}
        missing = set(SYNTHETIC_PURPOSES) - granted
        if missing:
            problems.append(f"lawful_basis does not grant {sorted(missing)}")
        if not body.get("proof_mechanisms"):
            problems.append("lawful_basis has no proof mechanism")
    if "lawful_basis" not in (vcon_dict.get("extensions") or []):
        problems.append("extensions does not list lawful_basis")

    tags: list[str] = []
    for a in attachments:
        if a.get("purpose") == "tags" and isinstance(a.get("body"), list):
            tags.extend(str(t) for t in a["body"])
    if "synthetic:true" not in tags:
        problems.append("no tags attachment holding synthetic:true")

    for i, party in enumerate(vcon_dict.get("parties") or []):
        if party.get("validation") != "synthetic":
            problems.append(f"party {i} is not validation: synthetic")
    return problems
